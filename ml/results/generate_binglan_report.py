# 6. DISCUSSION POINTS FOR BINGLAN
# ══════════════════════════════════════════════════════════
doc.add_heading('6. Discussion Points for Binglan', level=1)

doc.add_heading('6.1 Rank = Confidence Order — Is a Different Ranking Strategy Needed?', level=2)
doc.add_paragraph(
    'Currently, the "rank" in our predictions file is simply the confidence-sorted order from XGBoost. '
    'Rank 1 = highest XGBoost probability. This means Hits@K metrics are entirely determined by the '
    'XGBoost probability ordering — there is no independent ranking mechanism.'
)
bold_para('Options to consider:', '')
bullet('Re-rank by MRR per drug: Instead of globally sorting all (Drug, Disease) pairs, rank diseases independently for each drug. A drug\'s top prediction would be the disease it\'s most likely to treat relative to that drug\'s other candidates, not the globally highest-scoring pair. This would diversify predictions across drugs instead of clustering around high-degree drugs.', level=0)
bullet('Ensemble ranking: Combine XGBoost probability with PyKEEN\'s native RotatE scoring (||h ∘ r - t||) as a second signal. Pairs ranked highly by both methods would be prioritized.', level=0)
bullet('Structural re-ranking: De-emphasize predictions for very common diseases (heart disease, hypertension) that may be ranked highly due to disease degree bias rather than genuine pharmacological signal.', level=0)
bold_para('Recommendation: ', 'At minimum, report per-drug Hits@K in addition to global Hits@K. The current global ranking favors common diseases, which may not be what drug repurposing researchers need.')

doc.add_heading('6.2 Structural Features Barely Contribute — Should XGBoost Be Dropped?', level=2)
doc.add_paragraph(
    'Structural features contribute 0.6% (RotatE) to 4.3% (CompGCN) of XGBoost importance. This raises '
    'the question: if the embeddings carry nearly all the signal, why not use a simpler decoder?'
)
bold_para('Arguments for keeping XGBoost:', '')
bullet('XGBoost with structural features (AUROC 0.9717) dramatically outperforms cosine decoder (AUROC 0.5058) — the ~82% AUROC lift comes from XGBoost\'s ability to learn nonlinear combinations of embedding features, not from the structural features themselves.')
bullet('Removing structural features entirely might reduce AUROC by only ~4%, but the Hadamard product and absolute difference features (which are XGBoost\'s main signal) require a nonlinear decoder.')
bullet('XGBoost provides feature importance analysis, which is valuable for interpretability and paper discussion.')

bold_para('Arguments for a simpler decoder:', '')
bullet('An MLP decoder (one hidden layer) achieves AUROC 0.9625 for CompGCN — only -0.0092 below XGBoost. If the goal is simplicity, MLP may be sufficient.')
bullet('A pure DistMult-style h * r * t scoring (which CompGCN already uses internally during training) would remove the decoder entirely, but we don\'t have comparable numbers yet.')
bullet('The structural features\' near-zero contribution means they can safely be removed without significant performance loss.')

bold_para('Recommendation: ', 'Keep XGBoost as the primary decoder (best performance, interpretable importance) but add an ablation study: XGBoost without structural features. If AUROC drops by <1%, it strengthens the narrative that the learned embeddings capture all relevant graph structure.')

doc.add_heading('6.3 Node2Vec Dropped from Analysis — Confirmation', level=2)
doc.add_paragraph(
    'Node2Vec is dropped from the paper analysis for one fundamental reason: it is not relation-aware. '
    'Node2Vec\'s random walks treat all 25 edge types identically — drugBindsGene, geneInteractsWithGene, '
    'and chemicalIncreasesExpression all appear as "Drug-Gene connection" in the walks. Since CardioKB has '
    '25 distinct relationship types with different biological meanings, this is a critical limitation.'
)
doc.add_paragraph(
    'Supporting evidence from results: Node2Vec achieves AUROC 0.9504 (vs. 0.9652 RotatE, 0.9717 CompGCN). '
    'Its XGBoost relies heavily on structural features (30% vs 0.6-4.3% for the relation-aware methods), '
    'confirming that Node2Vec embeddings lack the relational information that XGBoost must then extract from '
    'structural features. Node2Vec files remain on disk for reference but are excluded from paper analysis.'
)
bold_para('Recommendation: ', 'Confirmed — correct decision. Mention Node2Vec as a baseline in the paper\'s methods section but do not include it in the main results table. The comparison between RotatE (translational KGE) and CompGCN (GNN) is the meaningful comparison.')

